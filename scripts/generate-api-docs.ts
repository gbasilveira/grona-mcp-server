import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';
import { TOOL_CATALOG, RESOURCE_CATALOG, PROMPT_CATALOG } from '../src/catalog.js';
import { TOOL_SCHEMAS } from '../src/server.js';
import { z } from 'zod';

type Schema = Record<string, any>;
const root = fileURLToPath(new URL('../', import.meta.url));
const spec = parse(readFileSync(`${root}docs/upstream/grona-api.yaml`, 'utf8'));
const resolve = (value: Schema): Schema => value?.$ref
  ? resolve(value.$ref.slice(2).split('/').reduce((node: any, key: string) => node[key], spec))
  : value;
const flat = (input: Schema): Schema => {
  const schema = resolve(input);
  if (!schema.allOf) return schema;
  return schema.allOf.map(flat).reduce((result: Schema, part: Schema) => ({
    ...result, ...part,
    properties: {...result.properties, ...part.properties},
    required: [...(result.required ?? []), ...(part.required ?? [])],
  }), {});
};
const line = (value: unknown): string => String(value ?? '').trim().replace(/\r?\n/g, ' ').replace(/\|/g, '\\|');
const type = (s: Schema): string => {
  s = flat(s);
  if (s.oneOf || s.anyOf) return (s.oneOf ?? s.anyOf).map(type).join(' or ');
  if (s.type === 'array') return `array<${type(s.items ?? {})}>`;
  return Array.isArray(s.type) ? s.type.join(' or ') : s.type ?? 'object';
};
const constraints = (s: Schema): string => {
  const r = resolve(s);
  return [r.enum ? `Values: ${r.enum.map((v: unknown) => `\`${v}\``).join(', ')}.` : '',
    r.pattern ? `Pattern: \`${r.pattern}\`.` : '',
    ...['minLength','maxLength','minimum','maximum','minItems','maxItems','minProperties','format','default'].filter(k=>r[k]!==undefined).map(k=>`${k}: \`${JSON.stringify(r[k])}\`.`),
    r.additionalProperties === false ? 'No additional keys.' : '',
  ].filter(Boolean).join(' ');
};
const fields = (input: Schema, prefix = '', depth = 0): string[] => {
  const s = flat(input);
  if (depth > 6) return [];
  const result: string[] = [];
  for (const [key, value] of Object.entries(s.properties ?? {})) {
    const raw = value as Schema;
    const r = flat(raw);
    const path = prefix ? `${prefix}.${key}` : key;
    const description = raw.description ?? r.description;
    result.push(`| \`${path}\` | ${line(type(r))} | ${s.required?.includes(key) ? 'yes' : 'no'} | ${line(description)} ${line(constraints(raw))} |`);
    if (r.properties) result.push(...fields(r, path, depth + 1));
    if (r.items) result.push(...fields(r.items, `${path}[]`, depth + 1));
  }
  return result;
};
const table = (s: Schema): string => ['| Field | Type | Required in parent | Meaning and constraints |','|---|---|---|---|',...fields(s)].join('\n');
const pretty = (v: unknown) => '```json\n' + JSON.stringify(v, null, 2) + '\n```';
const out: string[] = [
  '# Complete API → MCP reference',
  '> Generated by `npm run docs:generate`. Source: [Grona OpenAPI](https://developer.grona.ai/openapi/grona-api.yaml), captured 2026-11-12. Do not edit this file manually.',
  '[Exact MCP input schemas and discovery manifest](MCP-SCHEMAS.json) document every direct and helper argument. [Agent guide](AGENT-GUIDE.md) explains the helper workflows.',
  'All 10 documented operations are available. Direct tools return the upstream `{data,meta}` envelope unchanged. The mobile route uses its own host and credential. API path parameters are encoded as one path segment.',
  '## Route map',
  '| API host | Method | Route | MCP tool |', '|---|---|---|---|',
];
const operations: {path:string;method:string;op:Schema;pathItem:Schema;tool:any}[]=[];
for (const [path, value] of Object.entries(spec.paths)) {
  const pathItem=value as Schema;
  for (const method of ['get','post','patch','delete','put','head','options']) {
    if (!pathItem[method]) continue;
    const op=pathItem[method];
    const tool=TOOL_CATALOG.find(t=>t.operationId===op.operationId);
    if (!tool || tool.path!==path || tool.method!==method.toUpperCase()) throw new Error(`Missing/wrong route mapping: ${method} ${path}`);
    operations.push({path,method,op,pathItem,tool});
    out.push(`| ${pathItem.servers?.[0]?.url ?? spec.servers[0].url} | ${method.toUpperCase()} | \`${path}\` | \`${tool.name}\` |`);
  }
}
if (TOOL_CATALOG.filter(t=>t.kind==='api').length!==operations.length) throw new Error('Extra API tool absent from snapshot');
for (const {path,method,op,pathItem,tool} of operations) {
  out.push(`## ${tool.name}`,`**${method.toUpperCase()} \`${path}\` — ${op.summary}**`,op.description.trim());
  const parameters=[...(pathItem.parameters??[]),...(op.parameters??[])].map(resolve);
  if (parameters.length) out.push('### Path parameters','| Field | Type | Required | Meaning |','|---|---|---|---|',...parameters.map(p=>`| \`${p.name}\` | ${type(p.schema)} | ${p.required ? 'yes':'no'} | ${line(p.description)} |`));
  const body=op.requestBody?.content?.['application/json'];
  out.push('### MCP input',tool.name==='grona_update_campaign'
    ? 'Use `{ "campaignId": "…", "changes": { … } }`; the fields below belong inside `changes`.'
    : tool.name==='grona_set_campaign_status' ? 'Use `{ "campaignId": "…", "status": "live" }`.'
    : body ? 'Use the following JSON fields as the tool arguments.' : parameters.length ? 'Use `{ "campaignId": "…" }`.' : 'Use `{}` (no arguments).');
  if(body) {
    out.push(table(body.schema));
    const schema=resolve(body.schema);
    if(schema.description) out.push(schema.description.trim());
    if(schema.anyOf) out.push('Alternative required fields: '+schema.anyOf.map((s:Schema)=>(s.required??[]).map((v:string)=>`\`${v}\``).join(', ')).join(' **or** ')+'.');
    const examples=body.examples ? Object.entries(body.examples).map(([name,e])=>[name,(e as Schema).value]) : body.example ? [['Example',body.example]] : [];
    for(const [name,value] of examples) out.push(`#### ${name}`,pretty(value));
  }
  out.push('### Responses','| HTTP status | Meaning |','|---|---|',...Object.entries(op.responses).map(([code,v])=>`| ${code} | ${line(resolve(v as Schema).description)} |`));
  for (const [code, value] of Object.entries(op.responses)) {
    if (!code.startsWith('2')) continue;
    const response=resolve(value as Schema).content?.['application/json'];
    if(response) out.push(`### ${code} response fields`,table(response.schema));
  }
}
out.push('## Additional agent tools','These tools compose the API or compute locally. See [Agent guide](AGENT-GUIDE.md) for arguments, behavior and worked examples.','| Tool | Kind | Behavior |','|---|---|---|',...TOOL_CATALOG.filter(t=>t.kind!=='api').map(t=>`| \`${t.name}\` | ${t.kind} | ${line(t.description)} |`));
out.push('## Error contracts',table(spec.components.schemas.Error),'Mobile errors use the same shape. Unknown codes and extra response fields are preserved. Gateway failures may not be JSON. See [Operations](OPERATIONS.md) for the MCP error wrapper, retries, recovery and timeouts.');
const manifest = JSON.stringify({name:'grona-mcp',version:'1.0.0',tools:TOOL_CATALOG.map(t=>({...t,inputSchema:z.toJSONSchema(TOOL_SCHEMAS[t.name as keyof typeof TOOL_SCHEMAS],{io:'input'})})),resources:RESOURCE_CATALOG,prompts:PROMPT_CATALOG},null,2)+'\n';
const manifestPath=`${root}docs/MCP-SCHEMAS.json`;
const content=out.join('\n\n').replace(/\|\n\n\|/g,'|\n|')+'\n';
const destination=`${root}docs/API.md`;
if(process.argv.includes('--check')) {
  if(readFileSync(destination,'utf8')!==content || readFileSync(manifestPath,'utf8')!==manifest) throw new Error('API documentation is stale. Run npm run docs:generate.');
  process.stdout.write(`API documentation current: ${operations.length} routes, ${TOOL_CATALOG.length} tools.\n`);
} else {writeFileSync(destination,content);writeFileSync(manifestPath,manifest);process.stdout.write(`Generated docs/API.md for ${operations.length} routes.\n`);}
